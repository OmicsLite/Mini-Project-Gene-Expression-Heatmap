plt.show()

"""Sampel jaringan payudara normal dan kanker memiliki pola ekspresi gen yang berbeda.
- Sampel Normal cenderung mengelompok dengan sampel Normal lainnya.
- Sampel Tumor cenderung mengelompok dengan sampel Tumor lainnya.
- Warna merah dan biru menunjukkan adanya perbedaan tingkat ekspresi gen pada kedua kelompok.
Kesimpulan: Kanker payudara memiliki pola ekspresi gen yang berbeda dibandingkan jaringan normal. Perbedaan ini bisa menjadi petunjuk awal untuk mengidentifikasi gen yang berkaitan dengan kanker payudara.

Jadi, heatmap ini membantu kita melihat bahwa aktivitas gen pada jaringan normal dan kanker tidak sama.
"""

